<?php
// ------------------------------------------------------------
// PoiPHP boot file
// コントローラコンテキスト（$c）をここで1つだけ作る。
// poiphp.php 本体も、アプリの action() も、この同じ $c を使う。
// ------------------------------------------------------------

// SCRIPTFILE / SCRIPTDIR
if (!defined("SCRIPTFILE")) {
    define("SCRIPTFILE", basename($_SERVER["SCRIPT_FILENAME"]));
}

if (!defined("SCRIPTDIR")) {
    define("SCRIPTDIR", dirname($_SERVER["SCRIPT_FILENAME"]) . DIRECTORY_SEPARATOR);
}

// ------------------------------------------------------------
// config 読み込み（poiphp.php が先読み済みならそれを使う）
// ------------------------------------------------------------
if (!isset($config) || !is_array($config)) {
    $config = require POI_DIR . '/config.php';
}

// ------------------------------------------------------------
// Sanitize / Validate のインスタンス
// ------------------------------------------------------------
$sanitize = new Sanitize();
$s = $sanitize;

$validate = new Validate();
$v = $validate;

// ------------------------------------------------------------
// コントローラコンテキスト
// ------------------------------------------------------------
$c = new Controller();
$c->config = $config;
$c->setSanitize($sanitize);
$c->setValidate($validate);
$c->layout = $config['layout'] ?? null;

// ------------------------------------------------------------
// DB（PDO）について
// 接続は poiphp.php が $c->db に Database を登録するだけ（遅延接続）。
// DB を使うページでは $c->db->query(...) や $c->loadModel('User') が使える。
// 必要な時だけアプリ側で差し替えることもできる：
//   $c->db = new Database($dsn, $user, $pass);
// ------------------------------------------------------------

// ------------------------------------------------------------
// セッション開始
// ------------------------------------------------------------
$c->session = new Session();

// ------------------------------------------------------------
// CSRF トークン
// ------------------------------------------------------------
$c->csrf = $c->session->csrfToken();

// ------------------------------------------------------------
// ファイルアップロード
// ------------------------------------------------------------
$c->upload = new Upload();
